export type StdioServer = {
  command: string;
  args?: string[];
  cwd?: string;
  env?: Record<string, string>;
};

function tomlString(value: string): string {
  return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

function tomlArray(values: string[]): string {
  return `[${values.map(tomlString).join(", ")}]`;
}

export function renderCodexToml(servers: Record<string, StdioServer>): string {
  const lines = ["# Generated by lotl connect. Codex loads this for trusted projects.", ""];
  for (const [name, entry] of Object.entries(servers)) {
    lines.push(`[mcp_servers.${name}]`);
    lines.push(`command = ${tomlString(entry.command)}`);
    if (entry.args && entry.args.length > 0) {
      lines.push(`args = ${tomlArray(entry.args)}`);
    } else {
      lines.push("args = []");
    }
    if (entry.cwd) {
      lines.push(`cwd = ${tomlString(entry.cwd)}`);
    }
    lines.push("");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

export function upsertCodexMcp(existing: string, block: string): string {
  let next = existing.replace(/\r\n/g, "\n");
  next = next.replace(/\n*\[mcp_servers\.(lotl|Roblox_Studio)\][\s\S]*?(?=\n\[|\s*$)/g, "\n");
  next = next.replace(/\n{3,}/g, "\n\n").trimEnd();
  return `${next}${next ? "\n\n" : ""}${block.trim()}\n`;
}

export function vscodeMcpFile(servers: Record<string, StdioServer>): {
  servers: Record<string, { type: "stdio"; command: string; args?: string[]; cwd?: string }>;
} {
  const out: {
    servers: Record<string, { type: "stdio"; command: string; args?: string[]; cwd?: string }>;
  } = { servers: {} };
  for (const [name, entry] of Object.entries(servers)) {
    out.servers[name] = {
      type: "stdio",
      command: entry.command,
      args: entry.args ?? [],
      cwd: entry.cwd,
    };
  }
  return out;
}
